#!/usr/bin/env python3
"""Emit the nominal engine type database consumed directly by Luau Analysis."""
import argparse
import json
from pathlib import Path
from generate_api_types import casing


def generate(api):
    rows = ['LUDOT_API_4']
    primitives = {'Nil', 'bool', 'int', 'float', 'String', 'StringName', 'NodePath'}
    for enum in api.get('global_enums', []):
        fields = ['G', enum['name'], str(int(enum.get('is_bitfield', False)))]
        for constant in enum.get('values', []):
            fields.extend([constant['name'], str(constant['value'])])
        rows.append('\t'.join(fields))
    classes = {entry['name']: entry for entry in api['classes']}
    def getter_type(owner, getter):
        # Many properties declare int; their getter returns the enum type.
        while owner in classes:
            for method in classes[owner].get('methods', []):
                if method['name'] == getter and not method.get('arguments'):
                    return method.get('return_value', {}).get('type')
            owner = classes[owner].get('inherits')
        return None
    for entry in api['builtin_classes'] + api['classes']:
        name = entry['name']
        if name in primitives:
            continue
        builtin = entry in api['builtin_classes']
        rows.append('\t'.join(['C', name, entry.get('inherits', ''), str(int(builtin))]))
        operators = {'+': '__add', '-': '__sub', '*': '__mul', '/': '__div'}
        for operator in entry.get('operators', []):
            if operator['name'] in operators and operator.get('right_type'):
                right = 'float' if operator['right_type'] == 'int' else operator['right_type']
                row = '\t'.join(['O', name, operators[operator['name']], right, operator['return_type']])
                if row not in rows:
                    rows.append(row)
        for prop in entry.get('members', []) + entry.get('properties', []):
            renamed = prop['name']
            if renamed.isidentifier():
                kind = prop.get('type', 'Variant')
                returned = getter_type(name, prop['getter']) if kind == 'int' and prop.get('getter') else None
                if returned and returned.startswith('enum::'):
                    kind = returned
                rows.append('\t'.join(['P', name, renamed, kind]))
        for method in entry.get('methods', []):
            renamed = method['name']
            if not renamed.isidentifier() or renamed.startswith('__'):
                continue
            result = method.get('return_value', {}).get('type', method.get('return_type', 'void'))
            args = [arg.get('type', 'Variant') + ('?' if 'default_value' in arg else '') for arg in method.get('arguments', [])]
            rows.append('\t'.join(['F', name, renamed, result, str(int(method.get('is_static', False))), str(int(method.get('is_vararg', False))), *args]))
        for constant in entry.get('constants', []):
            rows.append('\t'.join(['K', name, casing(constant['name'], True), constant.get('type', 'int')]))
        # Editor-only enums stay out of the Enum catalog, so exported games see the same names.
        for enum in entry.get('enums', []) if entry.get('api_type') != 'editor' else []:
            fields = ['E', name, enum['name'], str(int(enum.get('is_bitfield', False)))]
            for constant in enum.get('values', []):
                fields.extend([constant['name'], str(constant['value'])])
            rows.append('\t'.join(fields))
        # X rows list a signal's argument types, so analysis can type it as Signal<(args...)>.
        for signal in entry.get('signals', []):
            rows.append('\t'.join(['X', name, signal['name'], *[arg.get('type', 'Variant') for arg in signal.get('arguments', [])]]))
    for singleton in api.get('singletons', []):
        rows.append('\t'.join(['S', singleton['name'], singleton['type']]))
    return '\n'.join(rows) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('api', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--callbacks', type=Path)
    args = parser.parse_args()
    api = json.loads(args.api.read_text())
    args.output.write_text(generate(api), encoding='utf-8')
    if args.callbacks:
        rows = ['// Generated by tools/generate_api_manifest.py --callbacks. MIT license.', '#pragma once', 'struct LudotNativeCallback { const char *owner; const char *name; };', 'inline constexpr LudotNativeCallback ludot_native_callbacks[] = {']
        for entry in api['classes']:
            for method in entry.get('methods', []):
                if method.get('is_virtual'):
                    rows.append('\t{ ' + json.dumps(entry['name']) + ', ' + json.dumps(method['name']) + ' },')
        # Object notifications are dispatched by ScriptInstance, not extension API methods.
        rows.append('\t{ "Object", "_notification" },')
        rows.append('};')
        args.callbacks.write_text('\n'.join(rows) + '\n')


if __name__ == '__main__':
    main()
